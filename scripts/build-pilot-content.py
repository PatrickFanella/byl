#!/usr/bin/env python3
"""Compile the reviewed Downers Grove content records into their data migration."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "docs/content/downers-grove"
OUTPUT = ROOT / "backend/migrations/00003_illustrated_place_histories.sql"


def quoted(value):
    return "'" + str(value).replace("'", "''") + "'"


def render():
    histories = json.loads((CONTENT / "histories.json").read_text())
    media = json.loads((CONTENT / "media.json").read_text())
    sources = {s["url"]: s for s in json.loads((CONTENT / "sources.json").read_text())}
    sql = ["-- Generated by scripts/build-pilot-content.py; review docs/content/downers-grove first.", "-- +goose Up"]
    assets = {}
    captions = [
        "Main Street station, May 11, 2004. A later view of the rail corridor.",
        "The Tivoli marquee in August 2009.",
        "The former Downers Grove School, later Junior Elementary School, circa 1915, on the site now occupied by Fishel Park. The building no longer stands.",
        "Family portrait: Henry Williams Blodgett, son of Israel and Avis, painted in 1875 by Alden Finney Brooks. Smithsonian National Portrait Gallery.",
    ]
    for i, asset in enumerate(media, 1):
        path = ROOT / asset["file"]
        assert hashlib.sha256(path.read_bytes()).hexdigest() == asset["sha256"], path
        slug = path.stem
        media_id = f"00000000-0000-4000-8000-00000000f0f{i}"
        assets[slug] = media_id
        license_id = {"CC BY 2.0": "CC-BY-2.0", "Public domain": "PD", "CC BY-SA 3.0": "CC-BY-SA-3.0", "CC0": "CC0-1.0"}[asset["license"]]
        license_url = asset["license_url"] or "https://commons.wikimedia.org/wiki/File:Tivolitheatre.JPG#Licensing"
        caption = captions[i - 1]
        if asset["changes"] != "None; original image":
            caption += " Resized by Wikimedia."
        values = [media_id, "image", "https://byl.subcult.tv/media/files/library/images/" + path.name, "image/jpeg", asset["width"], asset["height"], caption, asset["creator"], license_id, license_url, asset["source_url"], "published"]
        sql.append("INSERT INTO media_assets (id, kind, public_url, mime_type, width, height, caption, credit, license, license_url, source_url, status) VALUES (" + ", ".join(quoted(v) for v in values) + ");")
    for story in histories:
        assert len(story["body"].split()) >= 250
        assert len(story["body"].split("\n\n")) >= 3
        assert len(story["source_urls"]) >= 2
        hero = assets[story["media_slug"]]
        if story.get("new"):
            keys = ["id", "place_id", "slug", "title", "body", "date_start", "date_display"]
            values = [story[k] for k in keys] + [story.get("date_precision", "year"), hero, "published"]
            sql.append("INSERT INTO moments (" + ", ".join(keys + ["date_precision", "hero_media_id", "status"]) + ") VALUES (" + ", ".join(quoted(v) for v in values) + ");")
            sql.append(f"INSERT INTO moment_topics (moment_id, topic_id) VALUES ({quoted(story['id'])}, {quoted(story['topic_id'])});")
        else:
            sql.append(f"UPDATE moments SET title = {quoted(story['title'])}, body = {quoted(story['body'])}, hero_media_id = {quoted(hero)}, updated_at = now() WHERE id = {quoted(story['id'])};")
        sql.append(f"INSERT INTO moment_media (moment_id, media_id, position) VALUES ({quoted(story['id'])}, {quoted(hero)}, 1);")
        sql.append(f"DELETE FROM moment_sources WHERE moment_id = {quoted(story['id'])};")
        for position, url in enumerate(story["source_urls"], 1):
            source = sources[url]
            values = [story["id"], position, source["title"], url, source["publisher"], source["retrieved_at"], source["note"]]
            sql.append("INSERT INTO moment_sources (moment_id, position, title, url, publisher, retrieved_at, note) VALUES (" + ", ".join(quoted(v) for v in values) + ");")
    sql += [
        "UPDATE places SET summary = 'A downtown railway stop shaped by the 1864 arrival of the Burlington line, the surviving 1911 passenger station, and generations of commuter travel.' WHERE id = '00000000-0000-4000-8000-00000000b0b1';",
        "UPDATE places SET summary = 'A working cinema and mixed-use landmark that opened in 1928 as talking pictures changed moviegoing.' WHERE id = '00000000-0000-4000-8000-00000000b0b2';",
        "UPDATE places SET summary = 'A downtown gathering place with an earlier school site, a concert pavilion, and a history of local remembrance.', address = '1036 Grove St, Downers Grove, IL' WHERE id = '00000000-0000-4000-8000-00000000b0b3';",
        "UPDATE places SET summary = 'A local-history campus with two distinct Blodgett houses: the 1846 home associated with the Underground Railroad and the 1892 Charles Blodgett house.' WHERE id = '00000000-0000-4000-8000-00000000b0b4';",
        "-- +goose Down",
        "-- Content may have been edited after publication. Restore selectively from the operator's pre-migration backup.",
        "-- +goose StatementBegin",
        "DO $$ BEGIN RAISE EXCEPTION 'Illustrated histories require a reviewed content restore; automatic down would overwrite later curator edits'; END $$;",
        "-- +goose StatementEnd",
    ]
    return "\n\n".join(sql) + "\n"


def render_collections():
    assets = json.loads((CONTENT / "collections.json").read_text())
    sql = ["-- Generated by scripts/build-pilot-content.py from reviewed collections.json.", "-- +goose Up"]
    place_positions, moment_positions = {}, {}
    for asset in assets:
        assert asset["caption"] and asset["credit"] and asset["source_url"].startswith("https://")
        assert asset["retrieved_at"]
        if asset["external"]:
            assert asset["kind"] in ("video", "document") and "file" not in asset
        else:
            path = ROOT / asset["file"]
            assert hashlib.sha256(path.read_bytes()).hexdigest() == asset["sha256"], path
            assert asset["license"] in ("PD", "CC-BY-2.0", "CC-BY-SA-4.0")
            assert asset["license_url"]
        columns = ["id", "kind", "external", "public_url", "mime_type", "caption", "credit", "license", "license_url", "source_url", "status", "width", "height"]
        values = {**asset, "status": "published"}
        def literal(key):
            value = values.get(key)
            if value is None: return "NULL"
            if isinstance(value, bool): return "true" if value else "false"
            return quoted(value)
        sql.append("INSERT INTO media_assets (" + ", ".join(columns) + ") VALUES (" + ", ".join(literal(key) for key in columns) + ");")
        for place in asset["places"]:
            place_positions[place] = place_positions.get(place, 0) + 1
            sql.append(f"INSERT INTO place_media (place_id, media_id, position) VALUES ({quoted(place)}, {quoted(asset['id'])}, {place_positions[place]});")
        for moment in asset["moments"]:
            moment_positions[moment] = moment_positions.get(moment, 1) + 1
            sql.append(f"INSERT INTO moment_media (moment_id, media_id, position) VALUES ({quoted(moment)}, {quoted(asset['id'])}, {moment_positions[moment]});")
    sql += ["-- +goose Down", "-- +goose StatementBegin", "DO $$ BEGIN RAISE EXCEPTION 'Collections require a reviewed selective restore; later curator attachments must be retained'; END $$;", "-- +goose StatementEnd"]
    return "\n\n".join(sql) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    collections = render_collections()
    collection_output = ROOT / "backend/migrations/00005_pilot_media_collections.sql"
    if args.check:
        assert OUTPUT.read_text() == expected, "Pilot migration differs from reviewed content; regenerate and review"
        assert collection_output.read_text() == collections, "Collection migration differs from reviewed records"
        print("PASS pilot histories, collections, file hashes and generated migrations")
    else:
        OUTPUT.write_text(expected)
        collection_output.write_text(collections)
